import { randomBytes } from "node:crypto";

export interface Storage {
  readonly driver: "local" | "s3" | "cloudinary";
  /** A fresh, unguessable key for a new object owned by `userId`. The key's prefix decides which backend serves it. */
  newKey(userId: string): string;
  put(key: string, data: Uint8Array, contentType: string): Promise<void>;
  get(key: string): Promise<Uint8Array>;
  /** Idempotent: deleting an object that is already gone succeeds. */
  delete(key: string): Promise<void>;
  /** Short-lived direct download URL if the backend supports it (S3 presign); null => stream through the API. */
  signedDownloadUrl(key: string, filename: string, ttlSeconds: number): Promise<string | null>;
  /** Resolves when the backend can accept writes; rejects otherwise (admin health). */
  ping(): Promise<void>;
}

/** Keys are generated by the server (`u/<userId>/<random>`); anything else is rejected, so keys can never traverse paths. */
export const KEY_PATTERN = /^u\/[A-Za-z0-9_-]{1,64}\/[a-f0-9]{32}$/;
/** Cloudinary objects use their own prefix, which is how a key is routed to the right backend (see router.ts). */
export const CLOUDINARY_KEY_PATTERN = /^cld\/[A-Za-z0-9_-]{1,64}\/[a-f0-9]{32}$/;

export function randomKey(prefix: "u" | "cld", userId: string): string {
  return `${prefix}/${userId}/${randomBytes(16).toString("hex")}`;
}

/** Write-then-delete round trip, for backends where that is a cheap and meaningful health probe. */
export async function probeWritable(s: Pick<Storage, "put" | "delete" | "newKey">): Promise<void> {
  const key = s.newKey("_health");
  await s.put(key, new Uint8Array([1]), "application/octet-stream");
  await s.delete(key);
}

export type StorageErrorCode =
  | "NOT_FOUND"
  | "RATE_LIMITED" // provider asked us to slow down
  | "PROVIDER_QUOTA" // the provider account/plan is out of storage or credits
  | "FILE_TOO_LARGE" // over the provider's per-file cap
  | "UNAVAILABLE" // network error, timeout or provider 5xx
  | "NOT_CONFIGURED" // credentials rejected, or the backend isn't set up
  | "REJECTED"; // anything else the provider refused

/** Sanitized storage failure: `message` never contains provider response bodies, URLs or credentials. */
export class StorageError extends Error {
  readonly retryable: boolean;
  constructor(
    readonly code: StorageErrorCode,
    message: string,
  ) {
    super(message);
    this.name = "StorageError";
    this.retryable = code === "RATE_LIMITED" || code === "UNAVAILABLE";
  }
}
